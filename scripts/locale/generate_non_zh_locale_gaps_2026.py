def merge_gaps(locale: str, entries: dict[str, str]) -> int:
    gap_path = GAPS_DIR / f"{locale}.json"
    existing = json.loads(gap_path.read_text(encoding="utf-8")) if gap_path.is_file() else {}
    updated = 0
    for key, value in entries.items():
        if existing.get(key) != value:
            existing[key] = value
            updated += 1
    gap_path.write_text(
        json.dumps(dict(sorted(existing.items())), ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    return updated


def validate_translation_source(en_keys: set[str]) -> None:
    unknown = sorted(set(TRANSLATIONS_BY_KEY) - en_keys)
    if unknown:
        raise SystemExit(f"translation table contains unknown keys: {unknown[:10]}")


def build_entries_for_locale(
    locale: str,
    missing_keys: list[str],
    en: dict[str, str],
) -> dict[str, str]:
    entries: dict[str, str] = {}
    untranslated: list[str] = []
    same_as_en: list[str] = []
    empty_values: list[str] = []

    for key in missing_keys:
        translations = TRANSLATIONS_BY_KEY.get(key)
        value = translations.get(locale) if translations else None
        if value is None:
            untranslated.append(key)
            continue
        if not value.strip():
            empty_values.append(key)
        if value == en[key]:
            same_as_en.append(key)
        entries[key] = value

    if untranslated:
        raise SystemExit(f"{locale}: missing translations for keys: {untranslated[:10]}")
    if empty_values:
        raise SystemExit(f"{locale}: empty translations for keys: {empty_values[:10]}")
    if same_as_en:
        raise SystemExit(f"{locale}: translations identical to en values: {same_as_en[:10]}")
    if len(entries) != EXPECTED_COUNTS[locale]:
        raise SystemExit(
            f"{locale}: expected {EXPECTED_COUNTS[locale]} keys, got {len(entries)}"
        )
    return dict(sorted(entries.items()))


def main() -> None:
    en = json.loads(EN_PATH.read_text(encoding="utf-8"))
    en_keys = {key for key in en if not key.startswith("meta.")}
    validate_translation_source(en_keys)

    batch: dict[str, dict[str, str]] = {}
    for locale in TARGET_LOCALES:
        shipped = json.loads((LOCALES_DIR / f"{locale}.json").read_text(encoding="utf-8"))
        missing_keys = sorted(en_keys - set(shipped))
        batch[locale] = build_entries_for_locale(locale, missing_keys, en)

    DATA_PATH.write_text(json.dumps(batch, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {DATA_PATH.relative_to(ROOT)}")

    for locale in TARGET_LOCALES:
        updated = merge_gaps(locale, batch[locale])
        print(
            f"{locale}: wrote {len(batch[locale])} keys; merged {updated} into "
            f"{(GAPS_DIR / f'{locale}.json').relative_to(ROOT)}"
        )


if __name__ == "__main__":
    main()
