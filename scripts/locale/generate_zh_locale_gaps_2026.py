def twify(s: str, phrases: list[tuple[str, str]]) -> str:
    out = s
    for src, dst in phrases:
        out = out.replace(src, dst)
    return out


def merge_gaps(locale: str, entries: dict[str, str]) -> int:
    gap_path = GAPS_DIR / f"{locale}.json"
    existing = json.loads(gap_path.read_text(encoding="utf-8")) if gap_path.is_file() else {}
    updated = 0
    for key, value in entries.items():
        if existing.get(key) != value:
            existing[key] = value
            updated += 1
    sorted_gaps = dict(sorted(existing.items()))
    gap_path.write_text(json.dumps(sorted_gaps, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return updated


def main() -> None:
    en = json.loads(EN_PATH.read_text(encoding="utf-8"))
    en_keys = {k for k in en if not k.startswith("meta.")}
    shipped_cn = json.loads((ROOT / "src/i18n/locales/zh-CN.json").read_text(encoding="utf-8"))
    still_missing = sorted(en_keys - set(shipped_cn.keys()) - set(ZH_CN.keys()))
    if still_missing:
        print(f"warning: {len(still_missing)} keys still missing from ZH_CN batch (e.g. ai.* via packs)")

    extra = sorted(set(ZH_CN.keys()) - en_keys)
    if extra:
        raise SystemExit(f"ZH_CN has unknown keys: {extra[:5]}")

    phrases = load_phrases()
    zh_tw = {k: twify(v, phrases) for k, v in ZH_CN.items()}

    batch = {"zh-CN": ZH_CN, "zh-TW": zh_tw}
    DATA_PATH.write_text(json.dumps(batch, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {DATA_PATH.relative_to(ROOT)} ({len(ZH_CN)} keys per locale)")

    for locale, entries in batch.items():
        n = merge_gaps(locale, entries)
        print(f"merged {n} keys into gaps/{locale}.json")

    ai_cn = json.loads(AI_CN.read_text(encoding="utf-8"))
    ai_tw = {k: twify(v, phrases) for k, v in ai_cn.items()}
    AI_TW.write_text(json.dumps(ai_tw, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {AI_TW.relative_to(ROOT)} ({len(ai_tw)} ai.* keys)")

    menu_gaps = json.loads(MENU_GAPS.read_text(encoding="utf-8"))
    for locale in ("zh-CN", "zh-TW"):
        ai_pack = ai_tw if locale == "zh-TW" else ai_cn
        extras = {**batch[locale], **ai_pack}
        if locale in menu_gaps:
            extras.update(menu_gaps[locale])
        n = merge_gaps(locale, extras)
        print(f"persisted {n} total keys (incl. ai+menu) into gaps/{locale}.json")


if __name__ == "__main__":
    main()
